// Generates dashboard/js/data.js — the reference tables the offline dashboard embeds — from the
// shared sources, so the dashboard never carries a hand-copied label or colour table:
//
//   data/landcover.json          BBArt land-cover types + AV main groups (labels, colours, order)
//   data/typoch.json             TypoCH habitat codes → German names, level-1 colours
//   data/countries.json          ISO 3166-1 alpha-2 → German country names
//   processing-web/js/config.js  Bauzonen slugs → labels, colours (keyed by the harmonised use code there)
//
// Usage:  node scripts/build_dashboard_data.mjs            writes dashboard/js/data.js
//         node scripts/build_dashboard_data.mjs --check    exits 1 when the committed file is stale
// `npm run build:dashboard-data` runs the first form; dashboard/tests/data.test.mjs (npm test) is the check.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUT_PATH = path.join(ROOT, "dashboard", "js", "data.js");
const readJson = (rel) => JSON.parse(readFileSync(path.join(ROOT, rel), "utf8"));

/** ARE harmonised Hauptnutzung code per zone slug: config.js keys the colours by code, the
 *  dashboard's area columns (`bauzonen_<slug>_m2`) by the slug of the zone name. */
const BAUZONE_CODE = {
  wohnzonen: "11", arbeitszonen: "12", mischzonen: "13", zentrumszonen: "14",
  zonen_fuer_oeffentliche_nutzungen: "15", eingeschraenkte_bauzonen: "16",
  tourismus_und_freizeitzonen: "17", verkehrszonen_innerhalb_der_bauzonen: "18",
};
/** The zone-free remainder the processing emits as "Ohne Bauzone" (slug ohne_bauzone); slate so it
 *  reads as "no zone" next to the ARE colours. */
const OHNE_BAUZONE = { label: "Ohne Bauzone", color: "#cbd5e1" };

const HEADER = `/* Generated by scripts/build_dashboard_data.mjs — do not edit by hand.
 * Sources: data/landcover.json, data/typoch.json, data/countries.json, processing-web/js/config.js.
 * Regenerate with \`npm run build:dashboard-data\`; \`npm test\` fails while this file is stale. */
`;

/** The file text (deterministic: source order, 2-space JSON). */
export async function buildDashboardData() {
  // config.js touches window / document / localStorage at import time — the unit-test stubs cover that.
  const { installBrowserStubs } = await import("../processing-web/tests/stubs.mjs");
  installBrowserStubs();
  const cfg = await import("../processing-web/js/config.js");

  const landcover = readJson("data/landcover.json");
  const typoch = readJson("data/typoch.json");
  const countries = readJson("data/countries.json");

  const main = {};
  for (const [slug, g] of Object.entries(landcover.maingroups)) main[slug] = { label: g.de, color: g.color };
  const types = {};
  for (const t of landcover.types) {
    if (!main[t.maingroup]) throw new Error(`landcover.json: type ${t.key} names unknown main group ${t.maingroup}`);
    if (types[t.key]) throw new Error(`landcover.json: duplicate type key ${t.key}`);
    types[t.key] = { label: t.de, main: t.maingroup };
  }

  const names = {};
  for (const t of typoch.types) {
    if (names[t.code] !== undefined) throw new Error(`typoch.json: duplicate code ${t.code}`);
    names[t.code] = t.de;
  }

  const bauzonen = {};
  for (const [slug, label] of Object.entries(cfg.BAUZONE_LABELS)) bauzonen[slug] = { label, color: cfg.bauzoneColor(BAUZONE_CODE[slug] || "") };
  bauzonen.ohne_bauzone = OHNE_BAUZONE;

  const country = {};
  for (const [code, n] of Object.entries(countries.countries)) country[code] = n.de;

  const data = {
    landcover: { mainOrder: Object.keys(main), main, types },
    typoch: { l1Colors: typoch.l1_colors, names },
    bauzonen,
    countries: country,
  };
  return HEADER + "window.DASHBOARD_DATA = " + JSON.stringify(data, null, 2) + ";\n";
}

const invokedDirectly = process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (invokedDirectly) {
  const text = await buildDashboardData();
  const rel = path.relative(ROOT, OUT_PATH).replace(/\\/g, "/");
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUT_PATH, "utf8").replace(/\r\n/g, "\n"); } catch (e) { /* missing counts as stale */ }
    if (current !== text) { console.error(`${rel} is stale — run: npm run build:dashboard-data`); process.exit(1); }
    console.log(`${rel} is up to date`);
  } else {
    writeFileSync(OUT_PATH, text);
    const d = JSON.parse(text.slice(text.indexOf("{"), text.lastIndexOf("}") + 1));
    console.log(`wrote ${rel}: ${Object.keys(d.landcover.types).length} land-cover types, ${Object.keys(d.typoch.names).length} TypoCH names, ${Object.keys(d.bauzonen).length} Bauzonen, ${Object.keys(d.countries).length} countries`);
  }
}
